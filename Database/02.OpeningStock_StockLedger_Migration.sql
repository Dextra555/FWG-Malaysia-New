-- ─────────────────────────────────────────────────────────────
-- SECTION 1 : OpeningStock TABLE
-- ─────────────────────────────────────────────────────────────
-- Business rules:
--   * One entry per Item + Warehouse (enforced by unique index)
--   * TotalValue is stored (OpeningQty x UnitCost) for reporting
--   * ReferenceNo is auto-generated by the API (OS0001, OS0002, ...)
--   * IsActive = 0 means soft-deleted (still visible in ledger history)
-- ─────────────────────────────────────────────────────────────

IF NOT EXISTS (SELECT 1 FROM INFORMATION_SCHEMA.TABLES WHERE TABLE_NAME = 'OpeningStock')
BEGIN
    CREATE TABLE OpeningStock (
        ID            INT             PRIMARY KEY IDENTITY(1,1),
        ReferenceNo   NVARCHAR(20)    NOT NULL,
        WarehouseID   INT             NOT NULL,
        ItemID        INT             NOT NULL,
        OpeningDate   DATE            NOT NULL,
        OpeningQty    DECIMAL(18,2)   NOT NULL,
        UnitCost      DECIMAL(18,4)   NOT NULL,
        TotalValue    DECIMAL(18,4)   NOT NULL,   -- stored = OpeningQty * UnitCost
        Remarks       NVARCHAR(500)   NULL,
        IsActive      BIT             NOT NULL DEFAULT 1,
        LASTUPDATE    DATETIME        NOT NULL DEFAULT GETDATE(),
        LastUpdatedBy NVARCHAR(50)    NULL,

        CONSTRAINT FK_OpeningStock_Warehouse
            FOREIGN KEY (WarehouseID) REFERENCES WarehouseMaster(ID),

        CONSTRAINT FK_OpeningStock_Item
            FOREIGN KEY (ItemID) REFERENCES ItemMaster(ID)
    );

    -- Unique: only one opening stock entry per Item per Warehouse
    CREATE UNIQUE INDEX UX_OpeningStock_WarehouseItem
        ON OpeningStock(WarehouseID, ItemID)
        WHERE IsActive = 1;    -- filtered: allows soft-delete then re-enter if needed

    -- Performance indexes for common queries
    CREATE INDEX IX_OpeningStock_WarehouseID ON OpeningStock(WarehouseID);
    CREATE INDEX IX_OpeningStock_ItemID      ON OpeningStock(ItemID);
    CREATE INDEX IX_OpeningStock_OpeningDate ON OpeningStock(OpeningDate);

    PRINT 'OpeningStock table created.';
END
ELSE
    PRINT 'OpeningStock already exists. Skipping.';


-- ─────────────────────────────────────────────────────────────
-- SECTION 2 : StockLedger TABLE
-- ─────────────────────────────────────────────────────────────
-- Business rules:
--   * Every stock movement creates one row here
--   * InQty  = quantity flowing INTO the warehouse
--   * OutQty = quantity flowing OUT of the warehouse
--   * Current stock = SUM(InQty) - SUM(OutQty) per Item per Warehouse
--   * ReferenceType identifies the source transaction type
--   * ReferenceID links back to the source record (e.g. OpeningStock.ID)
--   * This table is NEVER directly edited by the user --
--     it is always maintained by the API transactionally
--
-- TransactionType values used in Part 2:
--   'OPENING'       Opening Stock entry
--
-- Values reserved for future parts:
--   'STOCK_IN'      Stock In / GRN
--   'ISSUE'         Material Issue / Stock Out
--   'ISSUE_RETURN'  Issue Return
--   'TRANSFER_IN'   Transfer In
--   'TRANSFER_OUT'  Transfer Out
--   'ADJ_PLUS'      Positive Adjustment
--   'ADJ_MINUS'     Negative Adjustment
--   'PURCHASE_RTN'  Purchase Return
--   'DAMAGE_LOSS'   Damage / Loss
-- ─────────────────────────────────────────────────────────────

IF NOT EXISTS (SELECT 1 FROM INFORMATION_SCHEMA.TABLES WHERE TABLE_NAME = 'StockLedger')
BEGIN
    CREATE TABLE StockLedger (
        ID              INT             PRIMARY KEY IDENTITY(1,1),
        TransactionNo   NVARCHAR(20)    NOT NULL,
        TransactionDate DATETIME        NOT NULL,
        TransactionType NVARCHAR(50)    NOT NULL,   -- e.g. 'OPENING', 'ISSUE', 'STOCK_IN'
        WarehouseID     INT             NOT NULL,
        ItemID          INT             NOT NULL,
        InQty           DECIMAL(18,2)   NOT NULL DEFAULT 0,
        OutQty          DECIMAL(18,2)   NOT NULL DEFAULT 0,
        UnitCost        DECIMAL(18,4)   NULL,
        ReferenceType   NVARCHAR(50)    NULL,       -- human label e.g. 'Opening Stock'
        ReferenceID     INT             NULL,       -- FK to source record ID
        ReferenceNo     NVARCHAR(50)    NULL,       -- human reference number e.g. 'OS0001'
        Remarks         NVARCHAR(500)   NULL,
        LASTUPDATE      DATETIME        NOT NULL DEFAULT GETDATE(),
        LastUpdatedBy   NVARCHAR(50)    NULL,

        CONSTRAINT FK_StockLedger_Warehouse
            FOREIGN KEY (WarehouseID) REFERENCES WarehouseMaster(ID),

        CONSTRAINT FK_StockLedger_Item
            FOREIGN KEY (ItemID) REFERENCES ItemMaster(ID)
    );

    -- Performance indexes for ledger queries
    CREATE INDEX IX_StockLedger_WarehouseID       ON StockLedger(WarehouseID);
    CREATE INDEX IX_StockLedger_ItemID            ON StockLedger(ItemID);
    CREATE INDEX IX_StockLedger_TransactionDate   ON StockLedger(TransactionDate);
    CREATE INDEX IX_StockLedger_TransactionType   ON StockLedger(TransactionType);
    CREATE INDEX IX_StockLedger_ReferenceID       ON StockLedger(ReferenceID);

    -- Composite index for the most common query: stock balance per item per warehouse
    CREATE INDEX IX_StockLedger_WhsItem
        ON StockLedger(WarehouseID, ItemID, TransactionDate);

    PRINT 'StockLedger table created.';
END
ELSE
    PRINT 'StockLedger already exists. Skipping.';


